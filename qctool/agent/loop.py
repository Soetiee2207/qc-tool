def protocol():
    vocabulary = {a: {'required': s.required, 'optional': s.optional, **({'doc': s.doc} if s.doc else {})}
                  for a, s in sorted(ACTION_SPECS.items()) if a in UI_VERBS or a in _NON_UI_ADAPTERS}
    return ('You author executable QC tests using tools. Documents define expected truth; UI/API observations never redefine it. '
        'Preserve EVERY source action and expected outcome in order. Explore missing UI with browser_observe/browser_act. '
        'Use exact data-testid target, or exact role plus accessible name. For observed plain text without a role/testid, use target=<exact text> and by_name=<same exact text>. Never CSS/JS/guessed locator. '
        'application_url is the browser website; API servers are NOT the website. Use relative source routes for browser navigation. '
        'Reuse available authenticate macros for source login sequences; include expanded plain steps in draft_case. '
        'browser_act returns resulting state; do not observe the same unchanged page again. '
        'Docs/session/bound aliases are already supplied; avoid rereading them. Ordered independent tool calls may share a round. '
        'Use EXACT alias strings as value, e.g. active_user.email, active_user.password; never {{email}}, @alias, or fixture:alias. '
        'Never put credentials in tool arguments: use only bound fixture aliases. Never provision accounts or perform writes without reviewed policy. '
        'For each assert.*, source MUST be {"req_id":<this intent req_id>,"quote":<verbatim substring of expected>}. '
        'Do not fit expectations to current product. Weak or nonliteral oracle goes to human review. '
        'UI cases MUST start with explicit ui.session. For an explicit visible source label, use assert.visible AND assert.text with that exact documented literal, not only by_name metadata. '
        'Steps need contiguous seq, kind given/when/then, action and args. draft_case automatically dry-runs a valid draft on a fresh context; fix returned errors in this session. '
        'Successful dry_run finishes automatically; no final prose needed. Prefer small drafts, short arguments and only necessary tools. '
        'Network outcomes caused by a UI click: put capture_response (the response must occur) or capture_requests (the request must NOT occur) '
        'on that ui.click, shaped {"method":"POST","path":"/exact/path","origin":"<API server origin from list_api>","save_as":"res"}. '
        'Then assert with source=<save_as>: assert.http_status/assert.json_field for capture_response; '
        'assert.json_field path "$.request_count" expected 0 for capture_requests. Never replay a UI write as http.request. '
        'An empty input is assert.value with expected "". '
        'If data/environment prevents execution, explain without inventing facts. Action vocabulary: '
        + json.dumps(vocabulary, sort_keys=True, ensure_ascii=False))


def manual_case(intent, case_id, module, reason, *, status='manual'):
    case = TestCase(case_id, module, intent.get('title', intent['id']), intent['expected'],
        steps=[Step(1, StepKind.GIVEN, 'perform.unmapped', {'description': intent.get('given') or 'Source precondition'}),
               Step(2, StepKind.WHEN, 'perform.unmapped', {'description': intent.get('when') or intent.get('statement', '') or 'Source action'}),
               Step(3, StepKind.THEN, 'assert.unmapped', {'expected': intent['expected']})],
        execution='manual', traces_to=[intent['req_id']], source_quote=intent['expected'],
        source_ref=intent.get('source_ref', ''), obligation_ids=[intent['id']],
        source_intent=deepcopy(intent), generation_status=status, review_reasons=[reason])
    return case


def author_intent(intent, tools, llm, *, budget=None, critic=False):
    budget = budget or AgentBudget()
    store = tools.policy.store
    session = {'current_session': 'anonymous', 'authenticated_available': bool(tools.storage_state), 'anonymous_available': True}
    aliases = store.to_dict() if store else {}
    # Only bound aliases, no acquisition config, policy internals or secrets.
    bindings = aliases.get('bindings', {}).get(intent['req_id'], {})
    fixture_metadata = {a: aliases.get('aliases', {}).get(a) for a in sorted(set(bindings.values()))}
    messages = [{'role': 'system', 'content': protocol()}, {'role': 'user', 'content': json.dumps(public({
        'application_url': tools.policy.base_url, 'intent': intent, 'session': session, 'fixture_bindings': bindings, 'fixture_aliases': fixture_metadata,
        'app_hints': tools.knowledge.hints() if tools.knowledge else {}}, store), ensure_ascii=False, sort_keys=True)}]
    result = AuthoringResult(manual_case(intent, tools.case_id, tools.module, 'Authoring incomplete'), deepcopy(intent))
    started, consumed, previous_errors = time.monotonic(), 0, set()
    definitions = tool_definitions()
    try:
        for turn in range(1, budget.max_turns + 1):
            if time.monotonic() - started >= budget.max_seconds:
                result.stop_reason = 'TIME_BUDGET'
                break
            estimate = len(json.dumps(messages, ensure_ascii=False)) // 3 + len(json.dumps(definitions)) // 3
            if consumed + estimate + budget.completion_tokens > budget.max_tokens:
                result.stop_reason = 'TOKEN_BUDGET'
                break
            with capture_provider_attempts() as attempts:
                try:
                    response = llm.chat(deepcopy(public(messages, store)), definitions, max_tokens=budget.completion_tokens)
                finally:
                    result.provider_attempts.extend(deepcopy(attempts))
            consumed += sum(a.get('usage', {}).get('total_tokens', 0) for a in attempts) or estimate
            if not isinstance(response, dict) or response.get('role') != 'assistant':
                raise ValueError('Invalid assistant envelope')
            # reasoning_content stays runtime-only, never audit or knowledge.
            messages.append(public(response, store))
            calls = response.get('tool_calls', [])
            if not calls:
                result.stop_reason = 'MODEL_ABSTAINED'
                result.issues.append('Model returned no executable draft/tool call')
                break
            for call in calls:
                name = call['function']['name']
                args = {}
                try:
                    args = json.loads(call['function']['arguments'], object_pairs_hook=_unique_keys, parse_constant=_reject_constant)
                    if not isinstance(args, dict):
                        raise ValueError('Tool arguments must be an object')
                    answer = tools.call(name, args)
                except (ValueError, KeyError, TypeError):
                    answer = {'ok': False, 'error': 'Malformed tool arguments; return exact schema, no duplicate keys'}
                if name == 'draft_case' and tools.candidate is not None:
                    result.last_draft = public(tools.candidate.to_dict(), store)
                result.history.append({'turn': turn, 'tool': name, 'ok': answer.get('ok', True),
                    'failed_step': answer.get('failed_step'), 'error': answer.get('error'), 'errors': answer.get('errors', []),
                    'arguments': audit_arguments(name, args, store)})
                messages.append({'role': 'tool', 'tool_call_id': call['id'], 'content': json.dumps(answer, ensure_ascii=False, sort_keys=True)})
                if not answer.get('ok', True):
                    key = json.dumps([name, call['function']['arguments'], answer, [o.get('url') for o in tools.observations]], sort_keys=True)
                    if key in previous_errors:
                        result.stop_reason = 'REPEATED_ERROR'
                        return result
                    previous_errors.add(key)
                if tools.ready is not None:
                    result.case = deepcopy(tools.ready)
                    result.dry_run_passed = True
                    result.stop_reason = 'READY'
                    if critic and turn < budget.max_turns and consumed + 3000 <= budget.max_tokens and time.monotonic() - started < budget.max_seconds:
                        # Critic sees source and draft only, never current product
                        # assertion values. It can downgrade to review, not rewrite.
                        try:
                            definition = _tool('review_case', 'Assess source faithfulness; never rewrite business outcomes.',
                                {'faithful': {'type': 'boolean'}, 'concerns': {'type':'array','items':{'type':'string'}}}, ['faithful','concerns'])
                            with capture_provider_attempts() as critic_attempts:
                                try:
                                    review = llm.chat([{'role':'system','content':'Review whether all original actions/outcomes are tested. Source is authoritative. Return review_case only; concise concerns.'},
                                        {'role':'user','content':json.dumps(public({'source':intent,'case':result.case.to_dict()},store),ensure_ascii=False,sort_keys=True)}], [definition],max_tokens=700)
                                finally:
                                    result.provider_attempts.extend(deepcopy(critic_attempts))
                            call = review['tool_calls'][0]
                            verdict = json.loads(call['function']['arguments'],object_pairs_hook=_unique_keys,parse_constant=_reject_constant)
                            if call['function']['name'] != 'review_case' or set(verdict) != {'faithful','concerns'} or type(verdict['faithful']) is not bool or not isinstance(verdict['concerns'],list) or any(not isinstance(v,str) for v in verdict['concerns']):
                                raise ValueError('Invalid critic response')
                            if not verdict['faithful'] or verdict['concerns']:
                                result.case.generation_status='needs_review'
                                result.case.review_reasons.extend(public(verdict['concerns'],store) or ['Critic doubts source faithfulness'])
                            result.history.append({'tool':'critic','ok':verdict['faithful'],'concerns':public(verdict['concerns'],store)})
                        except Exception:
                            result.case.generation_status='needs_review'
                            result.case.review_reasons.append('Critic unavailable; human review required')
                    return result
    except Exception as exc:
        result.stop_reason = 'PROVIDER_ERROR' if isinstance(exc, LLMProviderError) else 'AGENT_ERROR'
        result.issues.append(exc.safe_message if isinstance(exc, LLMProviderError) else type(exc).__name__)
        if not isinstance(exc, LLMProviderError):
            import traceback
            from pathlib import Path
            frame = traceback.extract_tb(exc.__traceback__)[-1]
            result.issues.append(f'{Path(frame.filename).name}:{frame.lineno}:{frame.name}')
    finally:
        tools.close()
    result.case.review_reasons = list(dict.fromkeys(result.issues or [result.stop_reason]))
    return result


def design_intents(intents, llm):
    """LLM proposes test titles/order; exact source G/W/T remains caller owned.

    All enumerated source obligations must occur once. No invented expectation,
    role, route or branch is accepted as a new obligation.
    """
    definition = _tool('design_tests', 'Design one intent for every supplied obligation, preserving source authority.',
        {'intents': {'type':'array','items': {'type':'object','properties': {
            'id': {'type':'string'}, 'title': {'type':'string'}, 'source_quote': {'type':'string'}},
            'required':['id','title','source_quote'],'additionalProperties':False}}}, ['intents'])
    messages = [{'role':'system','content':'Design tests from supplied business obligations only. Return design_tests tool call. Each supplied ID exactly once, source_quote verbatim from its expected text. Do not invent outcomes. Use concise titles.'},
                {'role':'user','content':json.dumps(intents,ensure_ascii=False,sort_keys=True)}]
    response=llm.chat(messages,[definition],tool_choice='auto',max_tokens=1200)
    attempts=[]
    calls=response.get('tool_calls',[])
    if len(calls)!=1 or calls[0]['function']['name']!='design_tests':
        raise ValueError('Design requires exactly one design_tests call')
    raw=json.loads(calls[0]['function']['arguments'],object_pairs_hook=_unique_keys,parse_constant=_reject_constant)
    if not isinstance(raw,dict) or set(raw)!={'intents'} or not isinstance(raw['intents'],list):
        raise ValueError('Malformed intent design')
    known={v['id']:v for v in intents}
    seen=set();result=[]
    for item in raw['intents']:
        if (not isinstance(item,dict) or set(item)!={'id','title','source_quote'}
            or item['id'] not in known or item['id'] in seen or not isinstance(item['title'],str)
            or not isinstance(item['source_quote'],str) or not item['source_quote']
            or item['source_quote'] not in known[item['id']]['expected']):
            raise ValueError('Design is not bound to exact original source')
        seen.add(item['id']);result.append({**known[item['id']],'title':item['title']})
    if seen!=set(known):
        raise ValueError('Design omitted an original obligation')
    return result,deepcopy(attempts)
