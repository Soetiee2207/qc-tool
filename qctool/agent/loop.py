class AgentLLM(Protocol):
    def chat(self, messages: list[dict], tools: list[dict], *, tool_choice='auto', max_tokens=1600) -> dict: ...


@dataclass(frozen=True)
class AgentBudget:
    max_turns: int = 6
    max_tokens: int = 22000
    max_seconds: float = 240
    completion_tokens: int = 2000

    def __post_init__(self):
        if (any(type(v) is not int for v in (self.max_turns, self.max_tokens, self.completion_tokens))
                or type(self.max_seconds) not in (int, float)):
            raise ValueError('Invalid per-intent agent budget types')
        if not (1 <= self.max_turns <= 20 and 1000 <= self.max_tokens <= 100000
                and 1 <= self.max_seconds <= 900 and 256 <= self.completion_tokens <= 8000):
            raise ValueError('Invalid per-intent agent budget')


@dataclass
class AuthoringResult:
    case: TestCase
    intent: dict
    history: list[dict] = field(default_factory=list)
    provider_attempts: list[dict] = field(default_factory=list)
    stop_reason: str = 'BUDGET'
    dry_run_passed: bool = False
    issues: list[str] = field(default_factory=list)
    last_draft: dict | None = None

    def to_dict(self):
        return {**asdict(self), 'case': self.case.to_dict()}


def _tool(name, description, properties=None, required=(), additional=False):
    return {'type': 'function', 'function': {'name': name, 'description': description,
            'parameters': {'type': 'object', 'properties': properties or {},
                           'required': list(required), 'additionalProperties': additional}}}


def tool_definitions():
    # Full per-action local schema is generated by case_schema(). Compact wire
    # schema avoids resending a 50-verb oneOf every round; Step.validate is final.
    draft = case_schema()
    draft['properties']['steps']['items'] = {'type': 'object', 'properties': {
        'seq': {'type': 'integer'}, 'kind': {'enum': ['given', 'when', 'then']},
        'action': {'enum': sorted(a for a in ACTION_SPECS if a in UI_VERBS or a in _NON_UI_ADAPTERS)},
        'args': {'type': 'object'}, 'source': {'type': 'object', 'properties': {
            'req_id': {'type': 'string'}, 'quote': {'type': 'string'}},
            'required': ['req_id', 'quote'], 'additionalProperties': False}},
        'required': ['seq', 'kind', 'action', 'args'], 'additionalProperties': False}
    return [
        _tool('read_docs', 'Read this original source intent.'),
        _tool('list_api', 'Read declared API operations, not observed business truth.'),
        _tool('browser_observe', 'Navigate if url supplied, then read redacted current ARIA and stable IDs.', {'url': {'type': 'string'}}),
        _tool('browser_act', 'Perform one live checked safe UI action; fixture values are aliases only.',
              {'action': {'enum': ['ui.goto', 'ui.session', 'ui.click', 'ui.fill', 'ui.select']}, 'args': {'type': 'object'}}, ['action', 'args']),
        {'type': 'function', 'function': {'name': 'draft_case', 'description': 'Draft complete testcase and run a fresh-context locator/action check; errors are feedback. Every assertion cites original expected text.', 'parameters': draft}},
        _tool('dry_run', 'Fresh-context execution of actions and locator availability only. No assertion values returned.'),
        _tool('use_macro', 'Reuse a known macro with live revalidation.', {'name': {'type': 'string'}}, ['name']),
    ]


def audit_arguments(name, args, store):
    if name not in {'browser_observe', 'browser_act', 'use_macro'}: return None
    from ..test_fixtures import is_alias
    value = deepcopy(args)
    if name == 'browser_act' and 'value' in value.get('args', {}) and not is_alias(value['args']['value']):
        value['args']['value'] = '[SOURCE_LITERAL]'
    return public(value, store)


